    public static bool IsRtl => Current == "fa";

    /// <summary>Keys present in one language but not the other (UI-test hook).</summary>
    public static List<string> MissingKeys()
    {
        var en = Map["en"].Keys.ToHashSet();
        var fa = Map["fa"].Keys.ToHashSet();
        return en.Except(fa).Select(k => "fa:" + k)
                 .Concat(fa.Except(en).Select(k => "en:" + k))
                 .OrderBy(k => k).ToList();
    }

    public static void Set(string lang)
    {
        Current = Map.ContainsKey(lang) ? lang : "en";
    }

    /// <summary>Formats a localized string. Supports 0..n arguments.</summary>
    public static string T(string key, params object[] args)
    {
        var lang = Map[Current];
        var s = lang.TryGetValue(key, out var v) ? v : Map["en"].GetValueOrDefault(key, key);
        if (args is null || args.Length == 0) return s;
        try { return string.Format(s, args); }
        catch (FormatException) { return s; }
    }
